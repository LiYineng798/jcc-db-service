-- Current likes/favorites and five-minute effective copies remain authoritative.
-- These append-only events support daily deltas and recent popularity separately.
CREATE TABLE orange_deck_activity_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deck_id BIGINT NOT NULL REFERENCES orange_decks(id),
    user_id BIGINT REFERENCES users(id),
    action TEXT NOT NULL CHECK (action IN ('published','hidden','restored','deleted','reviewed','like','favorite_add','favorite_remove')),
    created_at TEXT NOT NULL
);
CREATE INDEX idx_deck_activity_action ON orange_deck_activity_events(action, created_at, deck_id);
CREATE INDEX idx_deck_activity_history ON orange_deck_activity_events(deck_id, created_at, id);

ALTER TABLE copy_action_events ADD COLUMN deck_id BIGINT REFERENCES orange_decks(id);
ALTER TABLE copy_action_events ADD COLUMN code_type TEXT CHECK (code_type IN ('plan','lineup'));
ALTER TABLE copy_action_events ADD COLUMN actor_key TEXT;
ALTER TABLE copy_action_events ADD COLUMN client_action_id TEXT
    CHECK (client_action_id IS NULL OR length(trim(client_action_id)) BETWEEN 1 AND 64);
ALTER TABLE copy_action_events ADD COLUMN rank_eligible INTEGER NOT NULL DEFAULT 0
    CONSTRAINT copy_action_events_deck CHECK (
        rank_eligible IN (0,1) AND (
            (target_type='orange_deck' AND deck_id IS NOT NULL
                AND target_id=CAST(deck_id AS TEXT) AND code_type IS NOT NULL
                AND actor_key IS NOT NULL AND length(trim(actor_key))>0
                AND lineup_id IS NULL AND live_comp_id IS NULL
                AND (rank_eligible=0 OR success=1))
            OR (target_type<>'orange_deck' AND deck_id IS NULL AND code_type IS NULL AND rank_eligible=0)
        )
    );
CREATE UNIQUE INDEX idx_copy_action_client_action ON copy_action_events(client_action_id)
    WHERE client_action_id IS NOT NULL;
CREATE INDEX idx_copy_action_deck_created ON copy_action_events(target_type, created_at, deck_id);
CREATE INDEX idx_copy_action_deck_actor ON copy_action_events(deck_id, created_at, actor_key);

-- Daily distinct visits, not pageview/exposure events. NULL deck_id needs its own index.
CREATE TABLE orange_deck_visit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_date TEXT NOT NULL,
    visitor_key TEXT NOT NULL CHECK (length(trim(visitor_key))>0),
    user_id BIGINT REFERENCES users(id),
    surface TEXT NOT NULL CHECK (surface IN ('library','detail')),
    deck_id BIGINT REFERENCES orange_decks(id),
    device_type TEXT NOT NULL DEFAULT 'unknown' CHECK (device_type IN ('mobile','tablet','desktop','unknown')),
    created_at TEXT NOT NULL,
    CONSTRAINT orange_deck_visit_surface CHECK (
        (surface='library' AND deck_id IS NULL) OR (surface='detail' AND deck_id IS NOT NULL)
    )
);
CREATE UNIQUE INDEX idx_deck_visits_library ON orange_deck_visit_events(visit_date, visitor_key) WHERE surface='library';
CREATE UNIQUE INDEX idx_deck_visits_detail ON orange_deck_visit_events(visit_date, visitor_key, deck_id) WHERE surface='detail';
CREATE INDEX idx_deck_visits_surface ON orange_deck_visit_events(surface, created_at, deck_id);

