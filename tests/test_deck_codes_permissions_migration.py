import sqlite3
from pathlib import Path

import pytest

from scripts.migrate_sqlite_to_postgres import migrate_table


def database():
    db = sqlite3.connect(':memory:')
    db.row_factory = sqlite3.Row
    db.executescript('CREATE TABLE users(id INTEGER PRIMARY KEY); INSERT INTO users VALUES(1),(2);')
    for filename in ('0023_automation_accounts.sql', '0024_automation_sessions.sql', '0025_orange_decks.sql'):
        sql = (Path('migrations') / filename).read_text(encoding='utf-8')
        db.executescript(sql.replace('BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 'INTEGER PRIMARY KEY AUTOINCREMENT'))
    db.execute("INSERT INTO automation_accounts(user_id,expires_at,created_by) VALUES(2,'future',1)")
    db.execute("INSERT INTO orange_decks(user_id,name,portal_id,card_version,created_at,updated_at) VALUES(1,'旧卡组','stable','18','now','now')")
    db.executescript(Path('migrations/0026_deck_codes_and_permissions.sql').read_text(encoding='utf-8'))
    return db


def test_upgrade_preserves_existing_decks_and_defaults_to_no_upload_grant():
    db = database()
    assert tuple(db.execute('SELECT name,plan_code,season_id FROM orange_decks').fetchone()) == ('旧卡组', '', 'orange_s400001')
    assert tuple(db.execute('SELECT can_upload_decks,deck_seasons_json FROM automation_accounts').fetchone()) == (0, '[]')
    with pytest.raises(sqlite3.IntegrityError):
        db.execute('UPDATE automation_accounts SET can_upload_decks=2')


def test_sqlite_import_transfers_codes_and_grants():
    db = database()
    db.execute("UPDATE orange_decks SET plan_code='方案-大橘大利-MQ=='")
    db.execute('UPDATE automation_accounts SET can_upload_decks=1,deck_seasons_json=?', ('["orange_s400001"]',))
    captured = {}
    class Cursor:
        def executemany(self, sql, rows):
            captured['sql'], captured['rows'] = sql, rows
        def execute(self, *args):
            pass
        def fetchone(self):
            return (1,)
    for table, expected in [('orange_decks', '方案-大橘大利-MQ=='), ('automation_accounts', '["orange_s400001"]')]:
        assert migrate_table(db, Cursor(), table) == 1
        assert expected in captured['rows'][0]
