def test_import_orders_every_new_fk_and_restores_identity():
    source, target = database(), database()
    seed_submission(source)
    source.execute("INSERT INTO orange_deck_activity_events(id,deck_id,user_id,action,created_at) VALUES(30,1,2,'favorite_add','now')")
    source.execute("INSERT INTO orange_deck_visit_events(id,visit_date,visitor_key,surface,deck_id,created_at) VALUES(40,'2026-01-01','user:2','detail',1,'now')")
    target.execute('DELETE FROM orange_decks')
    # Importer must not load copies / notifications before their new parents.
    for child, parent in (
        ('orange_deck_submissions','orange_decks'), ('orange_deck_submission_events','orange_deck_submissions'),
        ('user_notifications','orange_deck_submissions'), ('notification_actors','user_notifications'),
        ('copy_action_events','orange_decks'), ('orange_deck_visit_events','orange_decks'),
        ('orange_deck_activity_events','orange_decks'),
    ):
        assert TABLE_ORDER.index(parent) < TABLE_ORDER.index(child)
    assert set(NEW_TABLES).issubset(IDENTITY_TABLES)
    assert len(TABLE_ORDER) == len(set(TABLE_ORDER))
    assert IDENTITY_TABLES.issubset(TABLE_ORDER)

    class Cursor:
        def __init__(self):
            self.cursor = target.cursor()
            self.sequences = {}

        def execute(self, sql, params=()):
            if 'setval(' in sql:
                self.sequences[params[0]] = params[2]
            else:
                return self.cursor.execute(sql, params)

        def executemany(self, sql, rows):
            return self.cursor.executemany(sql.replace('%s','?'), rows)

        def fetchone(self):
            return self.cursor.fetchone()

    cursor = Cursor()
    for table in TABLE_ORDER:
        if table in ('orange_decks', *NEW_TABLES):
            assert migrate_table(source, cursor, table) == 1
    assert cursor.sequences == {'orange_decks': 1, **dict(zip(NEW_TABLES, (10,20,30,40)))}
    assert not target.execute('PRAGMA foreign_key_check').fetchall()
    assert check(target, 'submission deck keeps season and provider') == 0


def test_activity_and_copy_checks_report_broken_imports():
    db = database()
    db.execute('PRAGMA foreign_keys=OFF')
    db.execute("INSERT INTO orange_deck_activity_events(deck_id,user_id,action,created_at) VALUES(999,999,'like','now')")
    assert check(db, 'deck activity references users and decks') == 1
    db.execute('''INSERT INTO copy_action_events(target_type,target_id,deck_id,code_type,actor_key,season_id,created_at)
        VALUES('orange_deck','1',1,'plan','user:2','wrong-season','now')''')
    assert check(db, 'deck copy actions reference matching decks') == 1
