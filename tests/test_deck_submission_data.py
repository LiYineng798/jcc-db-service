NEW_TABLES = ('orange_deck_submissions', 'orange_deck_submission_events',
              'orange_deck_activity_events', 'orange_deck_visit_events')


def database():
    db = upgraded_database()
    db.executescript('''
        CREATE TABLE lineups(id INTEGER PRIMARY KEY);
        CREATE TABLE copy_action_events(
            id INTEGER PRIMARY KEY AUTOINCREMENT,target_type TEXT NOT NULL,target_id TEXT NOT NULL,
            season_id TEXT,lineup_id INTEGER,live_comp_id TEXT,success INTEGER NOT NULL DEFAULT 1,
            created_at TEXT NOT NULL
        );
        INSERT INTO copy_action_events(target_type,target_id,created_at) VALUES('live_comp','old','now');
        CREATE TABLE user_notifications(id INTEGER PRIMARY KEY,user_id INTEGER,kind TEXT,deck_submission_id INTEGER);
    ''')
    sql = Path('migrations/0029_orange_deck_submissions.sql').read_text(encoding='utf-8')
    # SQLite cannot ALTER/DROP CHECK constraints. Web tests exercise that rebuild.
    sql = sql.split('ALTER TABLE user_notifications', 1)[0]
    sql += Path('migrations/0030_orange_deck_analytics.sql').read_text(encoding='utf-8')
    db.executescript(sql.replace('BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 'INTEGER PRIMARY KEY AUTOINCREMENT'))
    db.execute('PRAGMA foreign_keys=ON')
    return db


def seed_submission(db):
    db.execute("UPDATE orange_decks SET origin_type='submission',provided_by_user_id=2")
    db.execute('''INSERT INTO orange_deck_submissions
        (id,submitter_user_id,season_id,plan_code,lineup_code,code_fingerprint,request_key,deck_id,created_at,updated_at)
        VALUES(10,2,'orange_s400001','方案-大橘大利-MQ==','#ABC',?,'req-1',1,'now','now')''', ('a' * 64,))
    db.execute('''INSERT INTO orange_deck_submission_events
        (id,submission_id,actor_user_id,action,to_status,submission_version,created_at)
        VALUES(20,10,2,'submit','pending',1,'now')''')


def check(db, label):
    return db.execute(dict(CHECKS)[label]).fetchone()[0]


def test_legacy_rows_keep_owner_codes_and_default_analytics():
    db = database()
    row = db.execute('SELECT user_id,origin_type,provided_by_user_id,published_by_user_id,reviewed_at,lineup_code,plan_code FROM orange_decks').fetchone()
    assert tuple(row) == (1,'direct',None,None,None,'','方案-大橘大利-MQ==')
    assert tuple(db.execute('SELECT deck_id,code_type,actor_key,rank_eligible FROM copy_action_events').fetchone()) == (None,None,None,0)
    with pytest.raises(sqlite3.IntegrityError):
        db.execute("UPDATE orange_decks SET origin_type='submission'")
    with pytest.raises(sqlite3.IntegrityError):
        db.execute("UPDATE orange_decks SET reviewed_at='now'")


def test_attribution_and_event_history_integrity_detect_mismatches():
    db = database()
    seed_submission(db)
    labels = ('submission deck keeps season and provider', 'managed decks have their source submission',
              'submission event versions are complete and current', 'submission event history follows preceding state')
    assert all(check(db, label) == 0 for label in labels)
    db.execute('UPDATE orange_decks SET provided_by_user_id=1')
    assert check(db, labels[0]) == 1
    db.execute('UPDATE orange_deck_submissions SET version=2')
    assert check(db, labels[2]) == 1
    db.execute("UPDATE orange_deck_submission_events SET from_status='processing'")
    assert check(db, labels[3]) == 1


def test_event_version_is_unique_and_cannot_lose_parent():
    db = database()
