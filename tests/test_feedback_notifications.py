import sqlite3
from pathlib import Path

from scripts.migrate_sqlite_to_postgres import IDENTITY_TABLES, TABLE_ORDER


def test_feedback_migration_backfills_private_history_idempotently_and_keeps_guests_out():
    db=sqlite3.connect(':memory:')
    db.execute('PRAGMA foreign_keys=ON')
    db.executescript('''
        CREATE TABLE users(id INTEGER PRIMARY KEY);
        CREATE TABLE lineups(id INTEGER PRIMARY KEY,user_id INTEGER,name TEXT);
        CREATE TABLE reports(id INTEGER PRIMARY KEY,reporter_user_id INTEGER,lineup_id INTEGER,reason TEXT,status TEXT,created_at TEXT,handled_at TEXT);
        CREATE TABLE guestbook_messages(id INTEGER PRIMARY KEY,user_id INTEGER,content TEXT,created_at TEXT);
        INSERT INTO users VALUES(1);
        INSERT INTO lineups VALUES(2,1,'阵容');
        INSERT INTO reports VALUES(3,1,2,'失效','resolved','2026-10-18','2026-10-19');
        INSERT INTO guestbook_messages VALUES(4,1,'建议','2026-10-18');
        INSERT INTO guestbook_messages VALUES(5,NULL,'游客建议','2026-10-18');
    ''')
    sql=Path('migrations/0021_feedback_notifications.sql').read_text(encoding='utf-8')
    sql=sql.replace('BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY','INTEGER PRIMARY KEY AUTOINCREMENT')
    db.executescript(sql)
    assert db.execute('SELECT source_type,status FROM feedback_threads ORDER BY id').fetchall()==[('report','resolved'),('guestbook','pending')]
    assert db.execute('SELECT COUNT(*) FROM user_notifications WHERE notice_state=\'unread\'').fetchone()[0]==0
    db.execute("UPDATE feedback_threads SET status='in_progress', revision=2 WHERE source_type='guestbook'")
    db.executescript(sql)
    assert db.execute('SELECT COUNT(*) FROM feedback_threads').fetchone()[0]==2
    assert db.execute('SELECT COUNT(*) FROM user_notifications').fetchone()[0]==2
    assert db.execute("SELECT revision FROM feedback_threads WHERE source_type='guestbook'").fetchone()[0]==2
    db.execute("DELETE FROM feedback_threads WHERE source_type='guestbook'")
    assert db.execute('SELECT COUNT(*) FROM user_notifications').fetchone()[0]==1
    assert db.execute('PRAGMA foreign_key_check').fetchall()==[]


def test_feedback_import_order_and_identity_tables():
    for table in ('feedback_threads','feedback_events','user_notifications','author_favorite_receipts'):
        assert table in TABLE_ORDER
    assert TABLE_ORDER.index('feedback_threads')>TABLE_ORDER.index('guestbook_messages')
    assert TABLE_ORDER.index('user_notifications')>TABLE_ORDER.index('feedback_threads')
    assert {'feedback_threads','feedback_events','user_notifications'} <= IDENTITY_TABLES
    assert 'author_favorite_receipts' not in IDENTITY_TABLES
