import sqlite3
from pathlib import Path
import sys

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
from migrate_sqlite_to_postgres import TABLE_ORDER, IDENTITY_TABLES, migrate_table
from verify_integrity import CHECKS

DECK = '''INSERT INTO orange_decks (user_id,name,card_id_1,card_id_2,card_id_3,portal_id,card_version,status,created_at,updated_at)
          VALUES (?,?,?,?,?,?,'18.18.1',?,'now','now')'''


def database():
    # Execute the portable SQL clauses; only identity syntax differs on SQLite.
    db = sqlite3.connect(':memory:')
    db.row_factory = sqlite3.Row
    db.executescript('PRAGMA foreign_keys=ON; CREATE TABLE users(id INTEGER PRIMARY KEY); INSERT INTO users VALUES (1),(2);')
    sql = Path('migrations/0025_orange_decks.sql').read_text(encoding='utf-8')
    sql = sql.replace('BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 'INTEGER PRIMARY KEY AUTOINCREMENT').replace('BIGINT', 'INTEGER')
    db.executescript(sql)
    db.executescript(sql)
    return db


def test_migration_enforces_status_portal_cards_and_owner():
    db = database()
    db.execute(DECK, (1, '草稿', '7250036', None, None, 'stable', 'draft'))
    db.execute(DECK, (1, '公开', '7250036', '7250046', '7210001', 'unknown', 'published'))
    for params in [
        (1, '缺卡', '7250036', '7250046', None, 'stable', 'published'),
        (1, '重复', '7250036', '7250036', '7210001', 'stable', 'draft'),
        (1, '传送门', '7250036', '7250046', '7210001', 'portal', 'published'),
        (1, '状态', '7250036', '7250046', '7210001', 'stable', 'banned'),
        (9, '作者', '7250036', '7250046', '7210001', 'stable', 'published'),
    ]:
        with pytest.raises(sqlite3.IntegrityError):
            db.execute(DECK, params)
    with pytest.raises(sqlite3.IntegrityError):
        db.execute("UPDATE orange_decks SET formation_json='{}' WHERE id=1")
    with pytest.raises(sqlite3.IntegrityError):
        db.execute('UPDATE orange_decks SET featured=2 WHERE id=2')
    db.execute("INSERT INTO orange_deck_favorites VALUES (2,2,'now')")
    with pytest.raises(sqlite3.IntegrityError):
        db.execute("INSERT INTO orange_deck_favorites VALUES (2,2,'later')")
    with pytest.raises(sqlite3.IntegrityError):
        db.execute("INSERT INTO orange_deck_favorites VALUES (2,99,'now')")


def test_integrity_checks_cover_deck_references_and_featured_state():
    db = database()
    checks = {label: sql for label, sql in CHECKS if 'orange deck' in label}
    assert len(checks) == 5
    db.execute(DECK, (1, '公开', '7250036', '7250046', '7210001', 'unknown', 'published'))
    db.execute("INSERT INTO orange_deck_favorites VALUES (2,1,'now')")
    db.execute('INSERT INTO orange_decks (user_id,name,portal_id,card_version,status,forked_from_id,created_at,updated_at) '
               "VALUES (2,'副本','stable','18.18.1','draft',1,'now','now')")
    assert all(db.execute(sql).fetchone()[0] == 0 for sql in checks.values())
    db.execute("UPDATE orange_decks SET featured=1, status='hidden' WHERE id=1")
    assert db.execute(checks['featured orange decks are published']).fetchone()[0] == 1


def test_import_order_and_identity_restore_include_deck_tables():
    assert TABLE_ORDER.index('users') < TABLE_ORDER.index('orange_decks') < TABLE_ORDER.index('orange_deck_favorites')
    assert 'orange_decks' in IDENTITY_TABLES
    assert 'orange_deck_favorites' not in IDENTITY_TABLES
    db = database()
    db.execute(DECK, (1, '公开', '7250036', '7250046', '7210001', 'unknown', 'published'))
    db.execute('INSERT INTO orange_decks (user_id,name,portal_id,card_version,status,forked_from_id,created_at,updated_at) '
               "VALUES (2,'副本','stable','18.18.1','draft',1,'now','now')")

    class Cursor:
        def executemany(self, sql, rows):
            self.sql, self.rows = sql, rows

        def execute(self, sql, params=None):
            self.reset = (sql, params)

        def fetchone(self):
            return (2,)
    cursor = Cursor()
    assert migrate_table(db, cursor, 'orange_decks') == 2
    # Rows are copied in ID order, so a fork never precedes its source deck.
    assert [row[0] for row in cursor.rows] == [1, 2]
    assert cursor.reset[1] == ('orange_decks', 'id', 2)
